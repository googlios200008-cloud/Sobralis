package ru.sobralis.app;

import java.net.URI;
import java.util.Locale;
import java.util.regex.Pattern;

/** Origin policy for the isolated, synthetic connected prototype only. */
final class OnlinePolicy {
  private static final Pattern TEST_HOST=Pattern.compile("(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\\.)+test");
  private final String host;
  private final int port;
  private OnlinePolicy(String host,int port){this.host=host;this.port=port;}
  static OnlinePolicy fromOrigin(String origin){
    try{
      URI u=new URI(origin);String h=u.getHost();int p=u.getPort();
      if(!"https".equals(u.getScheme())||h==null||!h.equals(h.toLowerCase(Locale.ROOT))||!TEST_HOST.matcher(h).matches()||
         u.getRawUserInfo()!=null||!u.getRawAuthority().equals(h+(p==-1?"":":"+p))||u.getRawQuery()!=null||u.getRawFragment()!=null||
         !(u.getRawPath()==null||u.getRawPath().isEmpty())||p==0||p==443||p>65535)return null;
      return new OnlinePolicy(h,p==-1?443:p);
    }catch(Exception e){return null;}
  }
  boolean allows(String url){
    try{
      URI u=new URI(url);int p=u.getPort();String h=u.getHost();
      return "https".equalsIgnoreCase(u.getScheme())&&h!=null&&host.equalsIgnoreCase(h)&&u.getRawUserInfo()==null&&
        u.getRawAuthority().equalsIgnoreCase(h+(p==-1?"":":"+p))&&(p==-1?443:p)==port;
    }catch(Exception e){return false;}
  }
  // Accept only the same-origin fragment links generated by the application.
  // The landing URL keeps the token in the fragment; current API calls use
  // a JSON body. Never log request bodies or legacy token-bearing paths.
  String invitePath(String url){
    if(!allows(url))return null;
    try{
      URI u=new URI(url);String p=u.getRawPath(),fragment=u.getRawFragment();
      if(u.getRawQuery()!=null||!(p==null||p.isEmpty()||p.equals("/"))||fragment==null||
        !fragment.matches("(?:community-invite|trip-invite)=[A-Za-z0-9_-]{43}"))return null;
      return "/#"+fragment;
    }catch(Exception e){return null;}
  }
  boolean allowsNavigation(String url){
    if(!allows(url))return false;
    try{String p=new URI(url).getRawPath();return p==null||p.isEmpty()||p.equals("/")||p.equals("/index.html")||p.equals("/registration.html")||p.equals("/recovery.html")||p.equals("/verify-email")||p.equals("/reset-password");}catch(Exception e){return false;}
  }
}
